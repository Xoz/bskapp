// Engångsmigrering: kopierar produktionsdata från Turso → Supabase (Postgres).
// Körs med TURSO_DATABASE_URL/TURSO_AUTH_TOKEN (källan) och DATABASE_URL
// (målet – Supabase bsk-prod, Session pooler eller Direct connection).
//
//   TURSO_DATABASE_URL=... TURSO_AUTH_TOKEN=... DATABASE_URL=... \
//     node scripts/migrate-to-supabase.mjs
//
// Skapar schemat i målet om det inte redan finns (samma DDL som lib/db.ts,
// kopierad hit eftersom det här är ett fristående engångsskript – se
// SCHEMA_VERSION nedan, ska matcha lib/db.ts vid körningstillfället), kopierar
// sedan alla rader i FK-säker ordning och synkar identity-sekvenserna sist.
// Idempotent: kan köras om, dubbletter hoppas över (ON CONFLICT DO NOTHING).

import { createClient } from "@libsql/client";
import postgres from "postgres";

const { TURSO_DATABASE_URL, TURSO_AUTH_TOKEN, DATABASE_URL } = process.env;
if (!TURSO_DATABASE_URL || !DATABASE_URL) {
  console.error("Saknar TURSO_DATABASE_URL (+ TURSO_AUTH_TOKEN) eller DATABASE_URL.");
  process.exit(1);
}

const source = createClient({ url: TURSO_DATABASE_URL, authToken: TURSO_AUTH_TOKEN, intMode: "number" });
const target = postgres(DATABASE_URL, { prepare: false });

const SCHEMA_VERSION = "2026-06-20b";

