import { classifyMatch } from "./matchMetadata";
import { describe,it,expect } from "vitest";
import postgres from "postgres";
import {selectionDraftStatements} from "../selectionDraft";
import {applyRemovedMatches} from "./removed-matches";
import {applySnapshot} from "./import";
import type {ActivitySnapshot} from "./model";
// Testet skuggar tabeller med TEMP-tabeller på en enda anslutning.
describe.skipIf(!process.env.BSK_SYNC_TEST_DATABASE_URL)("synkens transaktion",()=>{
  it("bevarar uttagning, skriver inte närvaro från ja och tål återförsök",async()=>{
    const sql=postgres(process.env.BSK_SYNC_TEST_DATABASE_URL!,{max:1});
    try {
      await sql.unsafe(`CREATE TEMP TABLE settings(key text PRIMARY KEY,value text);
        CREATE TEMP TABLE groups(id int,name text,group_type text,active int);
        CREATE TEMP TABLE players(id int,name text,active int);
        CREATE TEMP TABLE development_activities(id text PRIMARY KEY,match_id int,external_key text UNIQUE,group_id int,activity_type text,activity_date text,start_time text,title text,external_source text);
        CREATE TEMP TABLE development_activity_callups(activity_id text,player_id int,attendance_status text);
        CREATE TEMP TABLE development_activity_callup_summaries(activity_id text PRIMARY KEY,accepted_count int,declined_count int,pending_count int,source text,updated_at text);
        CREATE TEMP TABLE matches(id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,date text,start_time text,opponent text,home_away text,location text,source text,external_uid text UNIQUE,cancelled int DEFAULT 0,match_type text DEFAULT 'seriespel',periods int DEFAULT 3,period_minutes int DEFAULT 20,group_id int,callup_accepted_count int,callup_declined_count int,callup_pending_count int,callup_source text);
        CREATE TEMP TABLE match_players(match_id int,player_id int,PRIMARY KEY(match_id,player_id));
        CREATE TEMP TABLE match_roster(match_id int,player_id int,callup_status text,selection_status text,selected_position text,source text,updated_at timestamptz, PRIMARY KEY(match_id,player_id));
        CREATE TEMP TABLE development_activity_participation(activity_id text,player_id int,attendance_status text,source text,PRIMARY KEY(activity_id,player_id));
        INSERT INTO groups VALUES(1,'Gul','subgroup',1); INSERT INTO players VALUES(1,'Exempel A',1),(2,'Exempel B',1);
        INSERT INTO development_activities(id,match_id,external_key,group_id) VALUES('a',7,'sanktan:123',1);INSERT INTO matches(id,group_id)VALUES(7,1);
        INSERT INTO match_roster VALUES(7,1,'accepted','selected','back','manual',now());`);
      const a:ActivitySnapshot={sourceId:"123",url:"https://www.svenskalag.se/bollstanassk-fotboll-f2014-gul/match/123/test",date:"2026-09-12",time:"09:00",title:"Test",kind:"match",callups:[{name:"Exempel A",status:"declined"},{name:"Exempel B",status:"accepted"}],totals:{accepted:1,declined:1,pending:0},attendance:null};
      await applySnapshot(sql,[a],"2026-09-10",true);
      expect((await sql`SELECT callup_status FROM match_roster WHERE player_id=1`)[0].callup_status).toBe("accepted");
      await applySnapshot(sql,[a],"2026-09-10");await applySnapshot(sql,[a],"2026-09-10");
      const rows=await sql`SELECT * FROM match_roster ORDER BY player_id`;
      expect(rows.length).toBe(2);expect(rows[0]).toMatchObject({callup_status:"declined",selection_status:"selected",selected_position:"back",source:"manual"});
      expect(rows[1].selection_status).toBeNull();expect(await sql`SELECT * FROM development_activity_participation`).toHaveLength(0);
      const bad={...a, totals:{accepted:2,declined:1,pending:0}};
      await expect(applySnapshot(sql,[bad],"2026-09-10")).rejects.toThrow();
      expect((await sql`SELECT callup_accepted_count FROM matches`)[0].callup_accepted_count).toBe(1);
      const training:ActivitySnapshot={...a,sourceId:"456",url:"https://www.svenskalag.se/bollstanassk-fotboll-f2014-gul/aktivitet/456/traning",date:"2026-09-09",kind:"training",title:"Träning",attendance:["Exempel A"]};
      await applySnapshot(sql,[training],"2026-09-10");
      await applySnapshot(sql,[training],"2026-09-10");
      expect(await sql`SELECT * FROM development_activities WHERE external_key='svenskalag:activity:456'`).toHaveLength(1);
      expect(await sql`SELECT * FROM development_activity_callups`).toHaveLength(2);
      await sql`UPDATE development_activity_participation SET source='manual', attendance_status='absent' WHERE player_id=1`;
      await applySnapshot(sql,[training],"2026-09-10");
      expect((await sql`SELECT * FROM development_activity_participation WHERE player_id=1`)[0]).toMatchObject({source:"svenskalag_browser",attendance_status:"present"});
      // Svenska Lag can create missing matches and correct their time; unknown people do not suppress known facts.
      const fresh:ActivitySnapshot={...a,sourceId:"999",url:a.url.replace('/123/','/999/'),match:{opponent:"Motståndare",homeAway:"away"},lineup:["Exempel B"]};
      await applySnapshot(sql,[fresh],"2026-09-10");
      await applySnapshot(sql,[{...fresh,time:"10:00"}],"2026-09-10");
      expect(await sql`SELECT * FROM matches WHERE external_uid='sanktan:999'`).toHaveLength(1);
      expect((await sql`SELECT start_time FROM matches WHERE external_uid='sanktan:999'`)[0].start_time).toBe("10:00");
      expect(await sql`SELECT * FROM settings WHERE key LIKE 'svenskalag_lineup:%'`).toHaveLength(1);
      await applySnapshot(sql,[{...fresh,cancelled:true}],"2026-09-10");
      expect((await sql`SELECT cancelled FROM matches WHERE external_uid='sanktan:999'`)[0].cancelled).toBe(1);
      await applySnapshot(sql,[fresh],"2026-09-10");
      expect((await sql`SELECT cancelled FROM matches WHERE external_uid='sanktan:999'`)[0].cancelled).toBe(0);
      const freshId=(await sql`SELECT id FROM matches WHERE external_uid='sanktan:999'`)[0].id;
      await sql`UPDATE match_roster SET source='manual',selection_status=NULL WHERE match_id=${freshId}`;
      await applySnapshot(sql,[fresh],"2026-09-10");
      expect((await sql`SELECT source FROM match_roster WHERE match_id=${freshId} AND player_id=2`)[0].source).toBe("svenskalag_browser");
      const removed={matchId:freshId,sourceId:"999",evidence:"source-deleted" as const};
      await applyRemovedMatches(sql,[removed],"2026-09-10",true);
      expect((await sql`SELECT cancelled FROM matches WHERE id=${freshId}`)[0].cancelled).toBe(0);
      await expect(applyRemovedMatches(sql,[removed,{...removed,matchId:7,sourceId:"wrong"}],"2026-09-10")).rejects.toThrow();
      await expect(applyRemovedMatches(sql,[removed,{...removed,matchId:7,sourceId:"888"}],"2026-09-10")).rejects.toThrow();
      expect((await sql`SELECT cancelled FROM matches WHERE id=${freshId}`)[0].cancelled).toBe(0);
      await applyRemovedMatches(sql,[removed],"2026-09-10");
      await applyRemovedMatches(sql,[removed],"2026-09-10");
      expect((await sql`SELECT cancelled FROM matches WHERE id=${freshId}`)[0].cancelled).toBe(1);
      expect(await sql`SELECT * FROM match_roster WHERE match_id=${freshId}`).toHaveLength(2);
      expect(await sql`SELECT * FROM settings WHERE key=${`svenskalag_removed:${freshId}`}`).toHaveLength(1);
      await applySnapshot(sql,[fresh],"2026-09-10");
      expect((await sql`SELECT cancelled FROM matches WHERE id=${freshId}`)[0].cancelled).toBe(0);
      expect(await sql`SELECT * FROM settings WHERE key=${`svenskalag_removed:${freshId}`}`).toHaveLength(0);
      // Ett uttryckligen tomt utkast är också ett utkast: ny synk får inte återvälja spelare.
      await sql.begin(async tx=>{
        for(const statement of selectionDraftStatements(freshId,[])) {
          let index=0;await tx.unsafe(statement.sql.replace(/\?/g,()=>`$${++index}`),statement.args);
        }
      });
      await applySnapshot(sql,[{...fresh,callups:[{name:"Exempel A",status:"accepted"},{name:"Exempel B",status:"accepted"}],totals:{accepted:2,declined:0,pending:0}}],"2026-09-10");
      expect(await sql`SELECT * FROM match_roster WHERE match_id=${freshId} AND selection_status='selected'`).toHaveLength(0);
      expect(await sql`SELECT * FROM match_roster WHERE match_id=${freshId} AND callup_status='accepted'`).toHaveLength(2);
      const emptyPresence={...training,attendance:[]};
      await applySnapshot(sql,[emptyPresence],"2026-09-10");
      expect((await sql`SELECT attendance_status FROM development_activity_participation WHERE player_id=1`)[0].attendance_status).toBe("absent");
      await sql`INSERT INTO players VALUES(3,'Tidigare spelare',0)`;
      await sql`INSERT INTO settings VALUES('svenskalag_non_player_names','["Ledare"]')`;
      const knownFormer={...training,attendance:['Exempel A','Tidigare spelare','Ledare']};
      expect((await applySnapshot(sql,[knownFormer],"2026-09-10")).unmatched).toEqual([]);
      expect(await sql`SELECT * FROM development_activity_participation WHERE player_id=3`).toHaveLength(0);
      expect((await applySnapshot(sql,[{...training,attendance:['Okänd spelare']}],"2026-09-10")).unmatched).toHaveLength(1);
      // Samma match får verifierad typ och längd; inga nya id:n eller cupimporter.
      const typed={...fresh,match:{...fresh.match!,metadata:classifyMatch('400955','Träningsmatcher 9v9')}};
      const beforeTyped=await sql`SELECT * FROM match_roster ORDER BY match_id,player_id`;
      await applySnapshot(sql,[typed],"2026-09-10",true);
      expect((await sql`SELECT period_minutes FROM matches WHERE id=${freshId}`)[0].period_minutes).toBe(20);
      await applySnapshot(sql,[typed],"2026-09-10");
      await applySnapshot(sql,[typed],"2026-09-10");
      expect((await sql`SELECT id,match_type,periods,period_minutes FROM matches WHERE external_uid='sanktan:999'`)[0]).toEqual({id:freshId,match_type:'traningsmatch',periods:3,period_minutes:25});
      expect(JSON.parse((await sql`SELECT value FROM settings WHERE key=${'svenskalag_match_metadata:'+freshId}`)[0].value).format).toBe(9);
      expect((await sql`SELECT selection_status FROM match_roster WHERE match_id=${freshId} AND player_id=1`)[0].selection_status).toBeNull();
      const beforeExcluded=await sql`SELECT * FROM matches ORDER BY id`;
      const cup={...typed,match:{...typed.match,metadata:classifyMatch('393366','Stockholm Football Cup (Friendly 1)')}};
      const unknown={...typed,sourceId:'1001',url:typed.url.replace('/999/','/1001/'),match:{...typed.match,metadata:classifyMatch('1000','Okänd tävling')}};
      await applySnapshot(sql,[cup],"2026-09-10",true);
      expect(JSON.parse((await sql`SELECT value FROM settings WHERE key=${'svenskalag_match_metadata:'+freshId}`)[0].value).scope).toBe('supported');
      expect((await applySnapshot(sql,[cup],"2026-09-10")).skippedCups).toBe(1);
      expect(JSON.parse((await sql`SELECT value FROM settings WHERE key=${'svenskalag_match_metadata:'+freshId}`)[0].value).scope).toBe('cup');
      const newCup={...cup,sourceId:'1002',url:cup.url.replace('/999/','/1002/')};
      expect((await applySnapshot(sql,[newCup],"2026-09-10")).skippedCups).toBe(1);
      expect((await applySnapshot(sql,[unknown],"2026-09-10")).unknownMatches).toBe(1);
      expect(await sql`SELECT * FROM matches ORDER BY id`).toEqual(beforeExcluded);
      expect(beforeTyped.length).toBe((await sql`SELECT * FROM match_roster`).length);
      // En Gulspelare får delta hos Grön utan att flyttas eller påverka Guls svar.
      await sql`INSERT INTO groups VALUES(2,'Grön','subgroup',1)`;
      await sql`INSERT INTO matches(id,date,group_id,source,external_uid) VALUES(88,'2026-09-09',2,'calendar','cal777-55555@svenskalag.se')`;
      const green:ActivitySnapshot={...a,sourceId:"777",url:"https://www.svenskalag.se/bollstanassk-fotboll-f2014-gron/match/777/test",date:"2026-09-09",match:{opponent:"Exempelmotstånd",homeAway:"home"},attendance:["Exempel A"]};
      await expect(applySnapshot(sql,[green],"2026-09-10")).rejects.toThrow();
      const yellowBefore=await sql`SELECT * FROM match_roster WHERE match_id=7 ORDER BY player_id`;
      await applySnapshot(sql,[green],"2026-09-10",false,"Grön");
      await applySnapshot(sql,[green],"2026-09-10",false,"Grön");
      const greenId=(await sql`SELECT match_id FROM development_activities WHERE external_key='sanktan:777' AND group_id=2`)[0].match_id;
      expect(greenId).toBe(88);
      expect(await sql`SELECT * FROM match_players WHERE match_id=${greenId} AND player_id=1`).toHaveLength(1);
      expect(await sql`SELECT * FROM match_roster WHERE match_id=7 ORDER BY player_id`).toEqual(yellowBefore);
      await applySnapshot(sql,[{...green,attendance:[]}],"2026-09-10",false,"Grön");
      expect((await sql`SELECT attendance_status FROM development_activity_participation ap JOIN development_activities da ON da.id=ap.activity_id WHERE da.match_id=${greenId} AND player_id=1`)[0].attendance_status).toBe("absent");
      await expect(applyRemovedMatches(sql,[{matchId:greenId,sourceId:"777",evidence:"source-deleted"}],"2026-09-10")).rejects.toThrow();
      await applyRemovedMatches(sql,[{matchId:greenId,sourceId:"777",evidence:"source-deleted"}],"2026-09-10",false,"Grön");
      expect((await sql`SELECT cancelled FROM matches WHERE id=${greenId}`)[0].cancelled).toBe(1);
    } finally {await sql.end();}
  });
});
